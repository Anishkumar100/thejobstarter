push('### Problem Statement');
push('');
push('Given a **sorted** array of numbers and a target, find two numbers that add up to exactly the target. Return their 0-based indices. You may not use the same element twice.');
push('');
push('```');
push('Input:  arr = [2, 7, 11, 15], target = 9');
