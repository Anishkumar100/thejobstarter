push('## 1.3 Space Complexity');
push('');
push('### What Space Complexity Actually Measures');
push('');
push('**Space Complexity** measures how much extra memory an algorithm needs as the input size grows — using the same Big O notation you just learned for time. Just like time complexity isn\'t measured in literal seconds, space complexity isn\'t measured in literal megabytes; it\'s measured in **how memory usage scales as n grows**.');
push('');
push('It\'s important to separate two things:');
push('');
push('- **Input space** — the memory needed just to store the data you were given. This is usually not counted against your algorithm.');
push('- **Auxiliary space** — any extra memory your algorithm uses while it runs: temporary variables, new arrays or objects you create, or the hidden memory used by recursive function calls.');
push('');
push('When people say "what\'s the space complexity of this algorithm?" — in interviews and in this course — they almost always mean **auxiliary space**.');
push('');
push('### A Simple Comparison: In-Place vs Creating New Memory');
push('');
push('Say you want to reverse an array of n elements.');
push('');
push('**Approach 1 — Swap elements in place**');
push('Swap the first and last, then the second and second-last, and so on.');
push('You only ever need a couple of temporary variables — regardless of whether the array has 10 or 10 million elements.');
push('This is **Constant Space — O(1)**.');
push('');
push('**Approach 2 — Create a brand new array**');
push('Copy elements into it in reverse order.');
push('The size of this new array grows directly with the input size.');
push('This is **Linear Space — O(n)**.');
push('');
push('Both approaches solve the same problem correctly and both run in O(n) time — but they have very different space complexity.');
push('');
push('### Common Space Complexities');
push('');
push('| Class | Name | Example |');
push('|---|---|---|');
push('| O(1) | Constant | A few variables (counters, pointers) |');
push('| O(n) | Linear | An array of size n, or a hash map storing n entries |');
push('| O(n²) | Quadratic | An n×n matrix |');
push('');
push('### The Hidden Cost: Recursion Stack');
push('');
push('Every time a function calls itself recursively, the computer needs to remember where to "return to" once that call finishes. This information is stored on the **call stack**, and it counts toward space complexity.');
push('');
push('For example, a recursive function that calls itself n times before returning has O(n) space complexity — even if it doesn\'t create any new arrays — because the call stack itself grows to n levels deep.');
push('');
push('### Key Takeaway');
push('');
push('Always ask: "Does this algorithm create new memory that grows with the input?" If yes, that\'s linear or worse space. If you\'re reusing the existing data structure and only using a few extra variables, that\'s constant space.');
push('');
