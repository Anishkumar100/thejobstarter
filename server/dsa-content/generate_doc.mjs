push('## 3.4 Subarray Sum Equals K');
push('');
push('| | |');
push('|---|---|');
push('| **Difficulty** | Medium |');
push('| **Subtopic** | Prefix Sum |');
push('| **Companies** | Amazon, Google, Microsoft, Facebook, Uber |');
push('');
push('### Problem Statement');
push('');
push('Given an array of integers (positive, negative, or zero) and a target `k`, count how many **contiguous subarrays** sum to exactly `k`.');
push('');
push('```');
push('Input:  arr = [1, 1, 1], k = 2');
push('Output: 2  (subarrays [1,1] at indices 0-1 and [1,1] at indices 1-2)');
push('```');
push('');
push('### Examples');
push('');
push('| Input | Output | Explanation |');
push('|---|---|---|');
push('| [1, 1, 1], k=2 | 2 | Two subarrays: [0,1] and [1,2] |');
push('| [1, 2, 3], k=3 | 2 | [0,1] = 1+2 and [2,2] = 3 |');
push('| [3,4,7,2,-3,1,4,2], k=7 | 4 | Four subarrays sum to 7 |');
push('');
push('### Constraints');
push('- 1 to 20,000 elements');
push('- Each element: -1000 to 1000');
push('- k: -10⁷ to 10⁷');
push('');
push('### Approach');
push('');
push('**Brute force:** Check every subarray — O(n²). For 20,000 elements, that\'s 200 million subarrays.');
push('');
push('**Prefix sum + hash map (optimal):**');
push('');
push('The key formula: sum(i, j) = prefix[j+1] - prefix[i]. If sum(i, j) = k, then prefix[j+1] - k = prefix[i].');
push('');
push('This means: when we\'re at position j, if (current_prefix - k) has appeared before, a subarray ending at j sums to k.');
push('');
push('```text');
push('FUNCTION subarray_sum(arr, k):');
push('    prefix_map = {0: 1}    # Seed for subarrays starting at index 0');
push('    prefix_sum = 0');
push('    count = 0');
push('');
push('    FOR EACH num IN arr:');
push('        prefix_sum = prefix_sum + num');
push('');
push('        IF (prefix_sum - k) IS IN prefix_map:');
push('            count = count + prefix_map[prefix_sum - k]');
push('');
push('        prefix_map[prefix_sum] = prefix_map[prefix_sum] + 1');
push('');
push('    RETURN count');
push('```');
push('');
push('**Trace on [3, 4, 7, 2, -3, 1, 4, 2] with k = 7:**');
push('');
push('```');
push('Init: prefix=0, map={0:1}, count=0');
push('');
push('i=0, val=3: prefix=3,  check 3-7=-4  → not found, map={0:1, 3:1}');
push('i=1, val=4: prefix=7,  check 7-7=0   → found! count=1,  subarray [3,4]');
push('i=2, val=7: prefix=14, check 14-7=7  → found! count=2,  subarray [7]');
push('i=3, val=2: prefix=16, check 16-7=9  → not found');
push('i=4, val=-3: prefix=13, check 13-7=6  → not found');
push('i=5, val=1: prefix=14, check 14-7=7  → found! count=3,  subarray [7,2,-3,1]');
push('i=6, val=4: prefix=18, check 18-7=11 → not found');
push('i=7, val=2: prefix=20, check 20-7=13 → found! count=4,  subarray [1,4,2]');
push('```');
push('');
push('**Why seed with {0: 1}?** This handles subarrays that start from index 0. When prefix_sum - k = 0, it means the subarray from index 0 to the current position sums to k.');
push('');
push('**Complexity:**');
push('- Time: O(n) — single pass with O(1) hash map operations');
push('- Space: O(n) — hash map stores up to n+1 prefix sums');
push('');
push('### Code Solution');
push('');
push('```python');
push('def subarray_sum(arr, k):');
push('    prefix_map = {0: 1}');
push('    prefix_sum = 0');
push('    count = 0');
push('');
push('    for num in arr:');
push('        prefix_sum += num');
push('');
push('        if (prefix_sum - k) in prefix_map:');
push('            count += prefix_map[prefix_sum - k]');
push('');
push('        prefix_map[prefix_sum] = prefix_map.get(prefix_sum, 0) + 1');
push('');
push('    return count');
push('```');
push('');
push('```javascript');
push('function subarraySum(arr, k) {');
push('    const prefixMap = new Map();');
push('    prefixMap.set(0, 1);');
push('    let prefixSum = 0;');
push('    let count = 0;');
push('');
push('    for (const num of arr) {');
push('        prefixSum += num;');
push('');
push('        if (prefixMap.has(prefixSum - k)) {');
push('            count += prefixMap.get(prefixSum - k);');
push('        }');
push('');
push('        prefixMap.set(prefixSum, (prefixMap.get(prefixSum) || 0) + 1);');
push('    }');
push('');
push('    return count;');
push('}');
push('```');
