// --- 1.4 Big O / Ω / Θ ---
push('## 1.4 Big O / Ω / Θ Notation');
push('');
push('### Beyond "Just" Big O');
push('');
push('So far you\'ve been using Big O informally — the idea that O(n) means "roughly proportional to n." Now let\'s make this precise, because Big O is actually one of **three related notations**, and knowing the difference will sharpen your understanding of algorithm analysis.');
push('');
push('Each notation describes a boundary on how an algorithm\'s running time (or space) behaves as input size grows — but each one describes a **different kind of boundary**.');
push('');
push('### Big O (O) — The Upper Bound (Worst Case)');
push('');
push('Big O describes the **maximum** amount of time an algorithm could possibly take. It answers: "No matter how unlucky the input is, the algorithm will never take longer than this."');
push('');
push('This is why Big O is used almost everywhere — it\'s a **guarantee**. If someone tells you "this runs in O(n²)," they\'re telling you the absolute ceiling: it will never behave worse than that.');
push('');
push('### Big Omega (Ω) — The Lower Bound (Best Case)');
push('');
push('Big Omega describes the **minimum** amount of time an algorithm could take — the best possible scenario. It answers: "Even in the best case, the algorithm can\'t do better than this."');
push('');
push('**Example:** Linear Search has a best case of Ω(1) — if the very first element you check happens to be the target, you\'re done in one step.');
push('');
push('### Big Theta (Θ) — The Tight Bound');
push('');
push('Big Theta is used when an algorithm\'s best-case and worst-case are the **same** growth rate — meaning there\'s no variance depending on the input. It answers: "This algorithm always behaves this way, regardless of input."');
push('');
push('**Example:** Finding the maximum value in an unsorted array — you must check every element, no shortcuts. Best case = O(n), worst case = O(n), so it\'s Θ(n).');
push('');
push('### Visual Comparison');
push('');
push('```');
push('      Time');
push('       ↑');
push('       |    ╱ O(n) — Upper bound (worst case)');
push('       |   ╱');
push('       |  ╱  Θ(n) — Tight bound');
push('       | ╱');
push('       |╱  Ω(1) — Lower bound (best case)');
push('       └──────────────────→ Input size');
push('```');
push('');
push('### Practical Advice');
push('');
push('- In interviews and this course, **Big O is what matters most**. Interviewers want to know the worst-case guarantee.');
push('- Ω and Θ are useful in academic contexts and when analyzing algorithms that have no variance.');
push('- When someone says "Big O of n," they usually mean Θ(n) — the typical case — unless they\'re being very precise.');
push('');
push('### Key Takeaway');
push('');
push('Big O = worst case (ceiling). Big Omega = best case (floor). Big Theta = tight bound (both are the same). For most practical purposes, focus on Big O — it\'s the guarantee your code won\'t surprise you.');
push('');
