// --- Problem 3: Longest Substring Without Repeating Characters ---
push('## 3.3 Longest Substring Without Repeating Characters');
push('');
push('| | |');
push('|---|---|');
push('| **Difficulty** | Medium |');
push('| **Subtopic** | Sliding Window |');
push('| **Companies** | Amazon, Google, Microsoft, Facebook, Apple |');
push('');
push('### Problem Statement');
push('');
push('Given a string, find the length of the **longest contiguous substring** that contains no repeating characters.');
push('');
push('```');
push('Input:  "abcabcbb"');
push('Output: 3  (the substring "abc")');
push('```');
push('');
push('### Examples');
push('');
push('| Input | Output | Explanation |');
push('|---|---|---|');
push('| "abcabcbb" | 3 | "abc", "bca", or "cab" — all length 3 |');
push('| "bbbbb" | 1 | Just a single "b" |');
push('| "pwwkew" | 3 | "wke" is length 3; "pwke" is a subsequence, not substring |');
push('| "dvdf" | 3 | "vdf" is length 3 |');
push('');
push('### Constraints');
push('- 0 to 50,000 characters');
push('- Letters (a-z, A-Z) and digits (0-9)');
push('');
push('### Approach');
push('');
push('**Brute force:** Check every substring and verify uniqueness — O(n³).');
push('');
push('**Sliding window solution (optimal):**');
push('');
push('Maintain a window that always has unique characters. When we find a repeat, shrink from the left until the repeat is gone.');
push('');
push('```text');
push('FUNCTION length_of_longest_substring(s):');
push('    char_set = EMPTY SET');
push('    left = 0');
push('    max_len = 0');
push('');
push('    FOR right FROM 0 TO length(s)-1:');
push('        WHILE s[right] IS IN char_set:');
push('            REMOVE s[left] FROM char_set');
push('            left = left + 1');
push('');
push('        ADD s[right] TO char_set');
push('        max_len = MAX(max_len, right - left + 1)');
push('');
push('    RETURN max_len');
push('```');
push('');
push('**Trace on "abcabcbb":**');
push('');
push('```');
push('right=0, a, set={a},        max=1');
push('right=1, b, set={a,b},      max=2');
push('right=2, c, set={a,b,c},    max=3');
push('right=3, a — repeat! shrink left to 1, set={b,c,a}, max=3');
push('right=4, b — repeat! shrink left to 2, set={c,a,b}, max=3');
push('right=5, c — repeat! shrink left to 3, set={a,b,c}, max=3');
push('right=6, b — repeat! shrink left to 5, set={c,b},   max=3');
push('right=7, b — repeat! shrink left to 7, set={b},     max=3');
push('```');
push('');
push('**Complexity:**');
push('- Time: O(n) — each char added once, removed at most once');
push('- Space: O(min(m, n)) — effectively O(1) since alphabet is bounded');
push('');
push('### Code Solution');
push('');
push('```python');
push('def length_of_longest_substring(s):');
push('    char_set = set()');
push('    left = 0');
push('    max_len = 0');
push('');
push('    for right in range(len(s)):');
push('        while s[right] in char_set:');
push('            char_set.remove(s[left])');
push('            left += 1');
push('');
push('        char_set.add(s[right])');
push('        max_len = max(max_len, right - left + 1)');
push('');
push('    return max_len');
push('```');
push('');
push('```javascript');
push('function lengthOfLongestSubstring(s) {');
push('    const charSet = new Set();');
push('    let left = 0;');
push('    let maxLen = 0;');
push('');
push('    for (let right = 0; right < s.length; right++) {');
push('        while (charSet.has(s[right])) {');
push('            charSet.delete(s[left]);');
push('            left++;');
push('        }');
push('');
push('        charSet.add(s[right]);');
push('        maxLen = Math.max(maxLen, right - left + 1);');
push('    }');
push('');
push('    return maxLen;');
push('}');
push('```');
