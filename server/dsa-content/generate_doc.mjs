// --- 2.3 Sliding Window ---
push('## 2.3 Sliding Window');
push('');
push('### What is a Sliding Window?');
push('');
push('Imagine you\'re looking through a train window as the train moves. At any moment, you see a specific stretch of the landscape — that\'s your "window." As the train moves, the window slides, revealing new scenery on one side and losing old scenery on the other. You never re-examine the entire journey at once — just the part visible through the window.');
push('');
push('A **sliding window** in programming is the same idea: it\'s a contiguous subarray that moves across the array one element at a time, or expands and contracts based on conditions. Instead of restarting from scratch for every subarray, you **reuse** the computation from the previous window.');
push('');
push('### Fixed Window vs Variable Window');
push('');
push('**Fixed Window Size:**');
push('');
push('```');
push('Array: [2, 5, 1, 8, 3, 7], k = 3');
push('');
push('Window 1: [2, 5, 1] → sum = 8');
push('Window 2: [5, 1, 8] → sum = 14  (added 8, removed 2)');
push('Window 3: [1, 8, 3] → sum = 12  (added 3, removed 5)');
push('Window 4: [8, 3, 7] → sum = 18  (added 7, removed 1)');
push('```');
push('');
push('Notice: instead of summing all three elements each time, just **add the new element** and **subtract the element that left**. That\'s O(1) per slide instead of O(k).');
push('');
push('**Variable Window Size:**');
push('');
push('The window grows or shrinks based on a condition (like "sum >= target" or "all unique characters"):');
push('');
push('```text');
push('Start with both pointers at index 0');
push('Expand right pointer until condition is met');
push('Contract left pointer until condition is broken');
push('Repeat until right pointer reaches the end');
push('```');
push('');
push('### Why Sliding Windows Work');
push('');
push('Brute force checks every possible subarray — O(n²) subarrays:');
push('');
push('```text');
push('FOR i FROM 0 TO n-1:');
push('    FOR j FROM i TO n-1:');
push('        # consider subarray arr[i..j]');
push('```');
push('');
push('The key insight: **contiguous subarrays that start at different positions are highly overlapping**. Most elements in arr[i..j] are also in arr[i+1..j+1]. Just adjust for what entered and left instead of recalculating from scratch.');
push('');
push('### When to Use Sliding Window');
push('');
push('✅ The problem involves a contiguous subarray or substring');
push('✅ You need to find a subarray that satisfies a condition (max, min, longest, shortest)');
push('✅ The problem mentions "subarray" or "substring"');
push('');
push('### Complexity');
push('- **Time:** O(n) — each element enters and leaves the window at most once');
push('- **Space:** O(1) or O(k) depending on what you store in the window');
push('');
push('### Key Takeaway');
push('');
push('Whenever you read "contiguous subarray" or "substring" in a problem, your first thought should be: "Can I use a sliding window?" It turns O(n²) brute-force into clean, O(n) code.');
push('');
hr();

// --- 2.4 Prefix Sum ---
push('## 2.4 Prefix Sum');
push('');
push('### What is Prefix Sum?');
push('');
push('Imagine you\'re a teacher grading quizzes. A student asks, "What\'s my total on questions 5 through 12?" You could add those 8 questions individually — 8 additions per question. If 30 students ask, you\'re doing hundreds of additions.');
push('');
push('A smarter way: before class, compute a **running total** as you go through the answer key. After question 1, write the subtotal. After question 2, write the new subtotal. Now when a student asks about questions 5-12, you just look up the total through question 12 and subtract the total through question 4. Two lookups, one subtraction — done.');
push('');
push('That\'s the prefix sum technique.');
push('');
push('### How It Works');
push('');
push('Given an array `arr`, the prefix sum array `prefix` is:');
push('');
push('```');
push('prefix[0] = 0');
push('prefix[i] = sum of arr[0] + arr[1] + ... + arr[i-1]');
push('```');
push('');
push('Example:');
push('');
push('```');
push('arr    = [3,  1,  4,  1,  5,  9,  2]');
push('prefix = [0,  3,  4,  8,  9, 14, 23, 25]');
push('index    0   1   2   3   4   5   6   7');
push('```');
push('');
push('To build:');
push('- prefix[0] = 0');
push('- prefix[1] = prefix[0] + arr[0] = 0 + 3 = 3');
push('- prefix[2] = prefix[1] + arr[1] = 3 + 1 = 4');
push('- ... and so on');
push('');
push('### The Magic Formula: Range Sum in O(1)');
push('');
push('To get the sum from index `l` to `r` (inclusive):');
push('');
push('```');
push('sum(l, r) = prefix[r + 1] - prefix[l]');
push('```');
push('');
push('Why? prefix[r+1] is sum of indices 0 to r. prefix[l] is sum of indices 0 to l-1. Subtract them and you get elements l through r.');
push('');
push('Example: sum of indices 2 to 5:');
push('- prefix[6] = 23 (sum of indices 0-5)');
push('- prefix[2] = 4 (sum of indices 0-1)');
push('- 23 - 4 = 19 = 4 + 1 + 5 + 9 ✅');
push('');
push('### The Space-Time Tradeoff');
push('');
push('| Approach | Query Time | Memory |');
push('|---|---|---|');
push('| Without prefix sum | O(n) per query | O(1) |');
push('| With prefix sum | O(1) per query | O(n) for the array |');
push('');
push('This tradeoff is worth it when you need to answer **many** range sum queries on the **same** array.');
push('');
push('### Beyond Sums');
push('');
push('The prefix idea extends to any **reversible** operation: prefix products, prefix XORs, prefix counts. XOR is particularly useful because it\'s its own inverse (a XOR a = 0).');
push('');
push('### Deeper Application: Subarray Sum Equals K');
push('');
push('Combining prefix sums with a hash map lets you count subarrays that sum to exactly k in O(n) time:');
push('');
push('```text');
