// --- 2.2 Two Pointers ---
push('## 2.2 Two Pointers');
push('');
push('### What is the Two-Pointer Technique?');
push('');
push('Imagine you and a friend are standing at opposite ends of a long hallway lined with numbered boxes. You both walk toward each other, checking boxes as you go. Between the two of you, you can cover the entire hallway in one pass, meeting somewhere in the middle.');
push('');
push('That\'s the two-pointer technique: instead of using a single loop variable, you use **two indices** (pointers) that move through the array, often from opposite ends toward each other. This lets you solve problems in O(n) time that would otherwise require O(n²) with nested loops.');
push('');
push('### The Two Main Patterns');
push('');
push('**1. Opposite Direction (Left/Right)**');
push('');
push('Both pointers start at opposite ends and move toward each other:');
push('');
push('```');
push('[1, 3, 5, 7, 9]');
push(' ^             ^');
push('left         right');
push('```');
push('');
push('After each step, either `left` moves right or `right` moves left, depending on some condition. The pointers meet (or cross) in the middle.');
push('');
push('**Example problem:** Given a sorted array, find two numbers that add up to a target.');
push('');
push('**2. Same Direction (Fast/Slow)**');
push('');
push('Both pointers start at the same end, but one moves faster than the other. Useful for finding cycles, removing duplicates, or finding the middle of a linked list.');
push('');
push('### Why Two Pointers Work');
push('');
push('Nested loops check every possible pair — a classic O(n²) approach:');
push('');
push('```text');
push('FOR i FROM 0 TO n-1:');
push('    FOR j FROM i+1 TO n-1:');
push('        # check pair (i, j)');
push('```');
push('');
push('Two pointers eliminate the inner loop by using the fact that **the data is structured** (often sorted). Once a pointer moves past a certain point, those elements are no longer relevant.');
push('');
push('### Concrete Example');
push('');
push('Find two numbers in sorted `[1, 3, 4, 6, 8, 10]` that sum to 12:');
push('');
push('```');
push('Step 1: left=0(1), right=5(10) → sum=11 → too small, move left');
push('Step 2: left=1(3), right=5(10) → sum=13 → too big, move right');
push('Step 3: left=1(3), right=4(8)  → sum=11 → too small, move left');
push('Step 4: left=2(4), right=4(8)  → sum=12 → found!');
push('```');
push('');
push('4 steps instead of 15. For n=1000: ~999 steps instead of ~500,000.');
push('');
push('### When to Use Two Pointers');
push('');
push('✅ The array is sorted');
push('✅ You need to find a pair (or triplet) that satisfies a condition');
push('✅ You need to reverse or rotate in place');
push('✅ The problem involves partitioning or rearranging elements');
push('');
push('### Complexity');
push('- **Time:** O(n) — each pointer moves at most n times');
push('- **Space:** O(1) — only two variables for the indices');
push('');
push('### Key Takeaway');
push('');
push('The two-pointer technique is your first tool for moving from O(n²) to O(n). Whenever you see a problem involving arrays (especially sorted ones) and pairs, ask: "Can I use two pointers here?"');
push('');
