push('');
push('**Approach 2 — If the list is sorted, use binary search:**');
push('Check the middle element, and depending on whether your target is bigger or smaller, discard half the list and repeat.');
push('For 10 million numbers, this takes only about 24 steps (2^24 is roughly 16 million) — because you\'re cutting the problem in half every single time. We call this **Logarithmic Time — O(log n)**.');
push('');
push('Same task, same data — but a completely different growth rate depending on the approach.');
