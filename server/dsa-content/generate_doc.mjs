push('');
push('### Examples');
push('');
push('| Input | Output | Explanation |');
push('|---|---|---|');
push('| [2, 7, 11, 15], target=9 | [0, 1] | 2 + 7 = 9 |');
push('| [1, 3, 4, 5, 7, 10], target=8 | [2, 3] | 4 + 5 = 8 |');
push('| [1, 2, 3], target=10 | [] | No pair sums to 10 |');
push('');
push('### Constraints');
push('- 2 to 100,000 elements');
push('- Sorted in strictly increasing order');
push('- At most one valid pair exists');
push('');
push('### Approach');
push('');
push('**Brute force:** Check every pair — O(n²). For 100,000 elements, that\'s 5 billion pairs.');
push('');
push('**Two-pointer solution (optimal):**');
push('');
push('Since the array is sorted, we can use this logic:');
push('- If the sum of left + right is **too small**, we need a bigger left element (move left right).');
push('- If the sum is **too big**, we need a smaller right element (move right left).');
push('');
push('```text');
push('FUNCTION two_sum_sorted(arr, target):');
push('    left = 0');
push('    right = length(arr) - 1');
push('');
push('    WHILE left < right:');
push('        current_sum = arr[left] + arr[right]');
push('');
push('        IF current_sum == target:');
push('            RETURN [left, right]');
push('        ELSE IF current_sum < target:');
push('            left = left + 1');
push('        ELSE:');
push('            right = right - 1');
push('');
push('    RETURN []');
push('```');
push('');
push('**Why this works:** Every step eliminates one entire row of possibilities. When sum < target, arr[left] + ANY element to the right would be too small, so we can safely skip arr[left].');
push('');
push('**Complexity:**');
push('- Time: O(n)');
push('- Space: O(1)');
push('');
push('### Code Solution');
push('');
push('```python');
push('def two_sum_sorted(arr, target):');
push('    left = 0');
push('    right = len(arr) - 1');
push('');
push('    while left < right:');
push('        current_sum = arr[left] + arr[right]');
push('');
push('        if current_sum == target:');
push('            return [left, right]');
push('        elif current_sum < target:');
push('            left += 1');
push('        else:');
push('            right -= 1');
push('');
push('    return []');
push('```');
push('');
push('```javascript');
push('function twoSumSorted(arr, target) {');
push('    let left = 0;');
push('    let right = arr.length - 1;');
push('');
push('    while (left < right) {');
push('        const currentSum = arr[left] + arr[right];');
push('');
push('        if (currentSum === target) {');
push('            return [left, right];');
push('        } else if (currentSum < target) {');
push('            left++;');
push('        } else {');
push('            right--;');
push('        }');
push('    }');
push('');
push('    return [];');
push('}');
