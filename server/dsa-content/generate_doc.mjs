push('');
push('### Why We Measure Time This Way');
push('');
push('You can\'t measure an algorithm\'s speed in seconds — the same code runs faster on a gaming laptop than on a five-year-old phone. So instead of measuring actual time, we measure **how the number of operations grows as the input size (usually called n) grows**. This gives us a measurement that\'s true regardless of hardware, programming language, or how fast the machine running it happens to be.');
