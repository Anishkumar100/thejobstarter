push('## 3.1 Reverse an Array');
push('');
push('| | |');
push('|---|---|');
push('| **Difficulty** | Easy |');
push('| **Subtopic** | Array Basics |');
push('| **Companies** | Amazon, Google, Microsoft, Apple |');
push('');
push('### Problem Statement');
push('');
push('You are given an array of numbers. Reverse the order of its elements **in-place** — modify the original array directly, without creating a separate copy.');
push('');
push('```');
push('Input:  [1, 2, 3, 4, 5]');
push('Output: [5, 4, 3, 2, 1]');
push('```');
push('');
push('### Examples');
push('');
push('| Input | Output | Explanation |');
push('|---|---|---|');
push('| [1, 2, 3, 4, 5] | [5, 4, 3, 2, 1] | Swap 0↔4, then 1↔3 |');
push('| [7, 8, 9] | [9, 8, 7] | Swap 0↔2 |');
push('| [42] | [42] | Single element, already reversed |');
push('| [] | [] | Empty array |');
push('');
push('### Constraints');
push('- 0 to 100,000 elements');
push('- Each element: -10⁹ to 10⁹');
push('');
push('### Approach');
push('');
push('**Step 1 — The naive way:** Create a new array and copy elements in reverse. Works but uses O(n) extra memory — doesn\'t meet the in-place requirement.');
push('');
push('**Step 2 — Two-pointer approach (optimal):**');
push('');
push('1. Place `left` at index 0 and `right` at the last index.');
push('2. Swap the elements at these two positions.');
push('3. Move `left` right by 1, move `right` left by 1.');
push('4. Repeat until `left` >= `right`.');
push('');
push('```');
push('Initial:     [1, 2, 3, 4, 5]');
push('              L              R');
push('');
push('After swap:  [5, 2, 3, 4, 1]');
push('                 L        R');
push('');
push('After swap:  [5, 4, 3, 2, 1]');
push('                    L');
push('                    R');
push('Pointers meet — done!');
push('```');
push('');
push('**Why this works:** Each swap places two elements in their correct final position. After the first swap, positions 0 and n-1 are final — we never need to touch them again.');
push('');
push('```text');
push('FUNCTION reverse_array(arr):');
push('    left = 0');
push('    right = length(arr) - 1');
push('');
push('    WHILE left < right:');
push('        SWAP arr[left], arr[right]');
push('        left = left + 1');
push('        right = right - 1');
push('');
push('    RETURN arr');
push('```');
push('');
push('**Complexity:**');
push('- Time: O(n) — n/2 swaps');
push('- Space: O(1) — just two variables');
push('');
push('### Code Solution');
push('');
push('```python');
push('def reverse_array(arr):');
push('    left = 0');
push('    right = len(arr) - 1');
push('');
push('    while left < right:');
push('        arr[left], arr[right] = arr[right], arr[left]');
push('        left += 1');
push('        right -= 1');
push('');
push('    return arr');
push('```');
push('');
push('```javascript');
push('function reverseArray(arr) {');
push('    let left = 0;');
push('    let right = arr.length - 1;');
push('');
push('    while (left < right) {');
push('        [arr[left], arr[right]] = [arr[right], arr[left]];');
push('        left++;');
push('        right--;');
push('    }');
push('');
push('    return arr;');
push('}');
push('```');
